    needed = {l: target_new[l] - assign_ptr[l] for l in 'ABCD'}
    candidates = [l for l in 'ABCD' if needed[l] > 0]
    if not candidates:
        candidates = list('ABCD')
    chosen = max(candidates, key=lambda x: needed[x])

    nq = new_fmt[idx]
    old_ans = nq['ans']
    if old_ans == chosen:
        assign_ptr[chosen] += 1
        continue

    # Find indices of old correct and new target in options
    old_idx = {'A': 0, 'B': 1, 'C': 2, 'D': 3}[old_ans]
    new_idx = {'A': 0, 'B': 1, 'C': 2, 'D': 3}[chosen]

    # Swap the option texts so correct answer moves to chosen position
    nq['opts'][old_idx], nq['opts'][new_idx] = nq['opts'][new_idx], nq['opts'][old_idx]
    # Fix the letter prefix in swapped options
    letters = ['A', 'B', 'C', 'D']
    for i in range(4):
        text = nq['opts'][i]
        # Remove old prefix (first char + ') ') and add correct one
        content = re.sub(r'^[A-D]\) ', '', text)
        nq['opts'][i] = letters[i] + ') ' + content

    nq['ans'] = chosen
    assign_ptr[chosen] += 1

